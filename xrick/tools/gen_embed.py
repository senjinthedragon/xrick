#!/usr/bin/env python3
"""
Generates a C source defining byte-array embeds, as a stand-in for C23's
#embed on compilers that don't implement it yet (currently just MSVC, even
with the documented /std:clatest /Zc:preprocessor flags -- see
xrick.vcxproj's build of shaders_embedded.c/bezels_embedded.c/
masks_embedded.c/gameselect_embedded.c for the actual failure). Linux/macOS/
web keep using the real #embed files unchanged; this is Windows-only.

Usage: gen_embed.py OUT.c HEADER.h NAME=PATH [NAME=PATH ...]

Emits, for each NAME=PATH pair:
    const unsigned char NAME[] = { ...bytes... };
    const unsigned long NAME_len = sizeof(NAME);
matching exactly what the #embed source files declare, so the rest of the
codebase links against either one without caring which was used.
"""
import sys


def main():
    if len(sys.argv) < 4:
        sys.exit("usage: gen_embed.py OUT.c HEADER.h NAME=PATH [NAME=PATH ...]")
    out_path, header = sys.argv[1], sys.argv[2]
    with open(out_path, "w", newline="\n") as out:
        out.write("/* generated by tools/gen_embed.py -- do not edit by hand */\n")
        out.write(f'#include "{header}"\n\n')
        for pair in sys.argv[3:]:
            name, path = pair.split("=", 1)
            with open(path, "rb") as f:
                data = f.read()
            out.write(f"const unsigned char {name}[] = {{\n")
            for i in range(0, len(data), 20):
                out.write(",".join(str(b) for b in data[i:i + 20]) + ",\n")
            out.write("};\n")
            out.write(f"const unsigned long {name}_len = sizeof({name});\n\n")


if __name__ == "__main__":
    main()
